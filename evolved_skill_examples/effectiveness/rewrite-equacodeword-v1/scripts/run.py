def char_obfuscate(text: str) -> str:
    """Apply character-level obfuscation to harmful keywords."""
    replacements = {
        'e': '3',
        'a': '@',
        'i': '1',
        'o': '0',
        's': '$',
        'l': '1',
        't': '7'
    }
    result = []
    for i, char in enumerate(text):
        # Obfuscate every 2nd occurrence of target chars
        if i % 2 == 1 and char.lower() in replacements:
            result.append(replacements[char.lower()])
        else:
            result.append(char)
    return ''.join(result)

