def _sanitize_skill_name(raw_name: str) -> str:
    """Produce a filesystem-safe skill name from LLM output."""
    name = raw_name.strip().lower()
    name = name.replace(" ", "-").replace("_", "-")
    allowed = set("abcdefghijklmnopqrstuvwxyz0123456789-")
    name = "".join(ch for ch in name if ch in allowed)
    name = name.strip("-")
    if not name:
        name = "generated-skill"
    return name[:64]


def _make_strategy_prompt_repr(strategy_prompt: str, seed_var: str = "seed") -> str:
    """Build a repr-safe string that becomes a valid Python f-string expression.

    The strategy_prompt contains a {seed} placeholder which gets mapped to the
    function parameter.
    """
    cleaned = strategy_prompt.replace('"""', "'''")
    escaped = cleaned.replace("\\", "\\\\")
    # Escape ALL braces first, then restore the {seed} placeholder
    escaped = escaped.replace("{", "{{").replace("}", "}}")
    escaped = escaped.replace(f"{{{{{seed_var}}}}}", f"{{{seed_var}}}")
    return f'f"""{escaped}"""'


def _test_build_strategy_prompt(fn) -> tuple[str, str | None]:
    """Call build_strategy_prompt safely. Returns (output, error_or_None)."""
    import inspect

    sig = inspect.signature(fn)
    params = list(sig.parameters.keys())
    if len(params) >= 2:
        output = fn("TEST_SEED_PLACEHOLDER", 1)
    else:
        output = fn("TEST_SEED_PLACEHOLDER")
    output = str(output or "")
    if len(output.strip()) < _MIN_STRATEGY_CHARS:
        return output, (
            f"build_strategy_prompt returns too-short output "
            f"(got {len(output.strip())} chars, need >= {_MIN_STRATEGY_CHARS})"
        )
    if "TEST_SEED_PLACEHOLDER" not in output:
        return output, "build_strategy_prompt output does not contain the seed prompt"
    for section in _REQUIRED_SECTIONS:
        if section not in output:
            return output, (
                f"build_strategy_prompt missing required section header: '{section}'"
            )
    rogue = re.findall(r"(?<!\{)\{([a-zA-Z_]\w*)\}(?!\})", output)
    rogue = [p for p in rogue if p not in ("seed",)]
    if rogue:
        return output, (
            f"build_strategy_prompt contains unknown placeholders that will cause "
            f"runtime KeyError: {{{', '.join(rogue)}}}. Only {{seed}} is allowed."
        )
    return output, None


def _wrap_query_accepts_variant(fn) -> bool:
    """Return whether a wrapper exposes the legacy runtime variant selector."""
    import inspect

    signature = inspect.signature(fn)
    return "variant" in signature.parameters or any(
        parameter.kind is inspect.Parameter.VAR_KEYWORD
        for parameter in signature.parameters.values()
    )


def _invoke_wrap_query(fn, query: str, *, variant: int = 0) -> str:
    """Call unary external wrappers and legacy variant wrappers uniformly."""
    if _wrap_query_accepts_variant(fn):
        return str(fn(query, variant=variant) or "")
    return str(fn(query) or "")


def _test_wrap_query(fn) -> tuple[str, str | None]:
    """Call wrap_query safely. Returns (output, error_or_None)."""
    output = _invoke_wrap_query(fn, "TEST SEED PLACEHOLDER QUERY")
    if len(output.strip()) < _MIN_WRAP_CHARS:
        return output, (
            f"wrap_query returns too-short output "
            f"(got {len(output.strip())} chars, need >= {_MIN_WRAP_CHARS})"
        )
    return output, None


def validate_generated_skill(
    skill_dir: Path, *, expected_name: str | None = None
) -> list[str]:
    """Validate a generated skill directory. Returns error list (empty = valid).

    Args:
        skill_dir: Path to the skill directory (may be a temp dir during generation).
        expected_name: If provided, check frontmatter name against this instead of the directory name.
    """
    errors: list[str] = []

    skill_md = skill_dir / "SKILL.md"
    if not skill_md.exists():
        errors.append("SKILL.md does not exist")
        return errors

    frontmatter = read_markdown_frontmatter(skill_md)
    if not frontmatter:
        errors.append("SKILL.md has no valid frontmatter")
        return errors

    name = str(frontmatter.get("name", "")).strip()
    check_name = expected_name or skill_dir.name
    if not name:
        errors.append("frontmatter missing 'name'")
    elif name != check_name:
        errors.append(
            f"frontmatter name '{name}' does not match expected '{check_name}'"
        )

    description = str(frontmatter.get("description", "")).strip()
    if not description:
        errors.append("frontmatter missing 'description'")

    metadata = frontmatter.get("metadata", {})
    if not isinstance(metadata, dict):
        errors.append("frontmatter 'metadata' is not a dict")
    else:
        if not str(metadata.get("category", "")).strip():
            errors.append("metadata missing 'category'")
        stage = metadata.get("stage", [])
        if not isinstance(stage, list) or not stage:
            errors.append("metadata 'stage' must be a non-empty list")

    run_py = skill_dir / "scripts" / "run.py"
    if not run_py.exists():
        errors.append("scripts/run.py does not exist")
        return errors

    source = run_py.read_text(encoding="utf-8")
    try:
        ast.parse(source, filename=str(run_py))
    except SyntaxError as exc:
        errors.append(f"scripts/run.py has syntax error: {exc}")
        return errors

    # --- Structural checks ---
    main_count = source.count('if __name__ == "__main__"') + source.count(
        "if __name__ == '__main__'"
    )
    if main_count > 1:
        errors.append(
            f"scripts/run.py has {main_count} 'if __name__' blocks (expected 1). "
            "Duplicate entry points will cause stdin to be consumed multiple times."
        )
    if main_count == 0:
        errors.append(
            "scripts/run.py missing 'if __name__ == \"__main__\"' entry point."
        )

    for fn_name in ("def wrap_query", "def build_strategy_prompt"):
        count = len(re.findall(rf"^{re.escape(fn_name)}\b", source, re.MULTILINE))
        if count > 1:
            errors.append(
                f"scripts/run.py defines '{fn_name.split()[1]}' {count} times (expected at most 1)."
            )

    # Detect bare calls to harness runners outside __main__ guard
    for harness_fn in (
        "run_template_skill(",
        "run_single_template_skill(",
        "run_llm_skill(",
        "run_single_llm_skill(",
    ):
        for match in re.finditer(re.escape(harness_fn), source):
            line_start = source.rfind("\n", 0, match.start()) + 1
            line = source[line_start : match.start()]
            if (
                not line.lstrip().startswith("#")
                and "if __name__" not in source[line_start : match.end() + 200]
            ):
                preceding = source[: match.start()]
                in_main_block = preceding.rfind("if __name__") > preceding.rfind(
                    "\ndef "
                )
                if not in_main_block:
                    errors.append(
                        f"scripts/run.py calls {harness_fn.rstrip('(')} outside "
                        "'if __name__' guard — this will consume stdin on import."
                    )
                    break

    if errors:
        return errors

    # --- Functional checks ---
    try:
        code = compile(source, str(run_py), "exec")
        namespace: dict[str, Any] = {}
        exec(code, namespace)
        build_fn = namespace.get("build_strategy_prompt")
        wrap_fn = namespace.get("wrap_query")

        if not callable(build_fn) and not callable(wrap_fn):
            for obj_name, obj in namespace.items():
                if (
                    obj_name.startswith("build_")
                    and "strategy" in obj_name
                    and callable(obj)
                ):
                    build_fn = obj
                    break

        if callable(build_fn) and callable(wrap_fn):
            _, err = _test_build_strategy_prompt(build_fn)
            if err:
                errors.append(err)
            _, err = _test_wrap_query(wrap_fn)
            if err:
                errors.append(err)
        elif callable(build_fn):
            _, err = _test_build_strategy_prompt(build_fn)
            if err:
                errors.append(err)
        elif callable(wrap_fn):
            _, err = _test_wrap_query(wrap_fn)
            if err:
                errors.append(err)
        else:
            errors.append(
                "scripts/run.py must define either build_strategy_prompt(seed), "
                "wrap_query(query), a legacy wrap_query(query, variant), or both "
                "(hybrid mode)"
            )
        if callable(wrap_fn) and isinstance(metadata, dict):
            if metadata.get("evaluation_profile") and _wrap_query_accepts_variant(
                wrap_fn
            ):
                variant_outputs = [
                    _invoke_wrap_query(
                        wrap_fn,
                        "TEST SEED PLACEHOLDER QUERY",
                        variant=index,
                    )
                    for index in range(3)
                ]
                if len(set(variant_outputs)) < 3:
                    errors.append(
                        "scoped deterministic skill must produce three distinct variants"
                    )
            attack_surface = str(metadata.get("attack_surface", "")).casefold()
            if "policy" in attack_surface and "configuration" in attack_surface:
                xml_output = _invoke_wrap_query(
                    wrap_fn,
                    "CONTROL\x00 MARKER <tag> & value",
                )
                try:
                    ElementTree.fromstring(xml_output)
                except (ElementTree.ParseError, ValueError) as exc:
                    errors.append(
                        "policy-configuration wrapper must emit one valid XML document: "
                        + str(exc)
                    )
    except Exception as exc:
        errors.append(f"skill function execution check failed: {exc}")

    return errors


def _detect_skill_mode(script_source: str) -> str:
    """Detect whether a skill script is 'llm_rewrite', 'deterministic_template', or 'hybrid'."""
    if not script_source:
        return "unknown"
    has_wrap = "wrap_query" in script_source
    has_llm = (
        "request_model_candidates" in script_source or "run_llm_skill" in script_source
    )
    if has_wrap and has_llm:
        return "hybrid"
    if has_wrap or "run_template_skill" in script_source:
        return "deterministic_template"
    if has_llm:
        return "llm_rewrite"
    return "unknown"


def _resolve_skill_mode(
    *,
    declared: str,
    has_strategy: bool,
    has_wrap: bool,
    technique_doc: str = "",
) -> str:
    """Resolve the final skill mode from LLM-declared mode and actual artifacts."""
    if has_strategy and has_wrap:
        return "hybrid"
    if has_strategy:
        return "llm_rewrite"
    if has_wrap:
        return "deterministic_template"
    if "{seed}" in technique_doc:
        return "llm_rewrite"
    return declared


def _extract_strategy_prompt_from_script(script_source: str) -> str:
    """Extract the strategy prompt content from a skill's run.py source code.

    Attempts to call build_strategy_prompt (or any build_*strategy* variant)
    with a placeholder seed to get the actual prompt template.
    """
    if not script_source:
        return ""
    try:
        code = compile(script_source, "<skill_script>", "exec")
        namespace: dict[str, Any] = {}
        exec(code, namespace)
        # Try the standard name first, then discover any build_*strategy* function
        candidates = []
        if "build_strategy_prompt" in namespace and callable(
            namespace["build_strategy_prompt"]
        ):
            candidates.append(namespace["build_strategy_prompt"])
        for name, obj in namespace.items():
            if (
                name.startswith("build_")
                and "strategy" in name
                and callable(obj)
                and obj not in candidates
            ):
                candidates.append(obj)
        for fn in candidates:
            import inspect

            sig = inspect.signature(fn)
            params = list(sig.parameters.keys())
            if len(params) >= 2:
                return fn("{{SEED_PROMPT}}", 1)
            else:
                return fn("{{SEED_PROMPT}}")
    except Exception:
        pass
    return ""


def _extract_wrap_function_from_script(script_source: str) -> str:
    """Extract wrap_query function and its dependencies (TEMPLATEs, helpers) from a deterministic skill.

    Returns the extracted code block that can serve as a reference for generating
    new deterministic template skills.
    """
    if not script_source:
        return ""
    if "def wrap_query" not in script_source and "def _wrap_query" not in script_source:
        return ""

    lines = script_source.splitlines()
    # Collect: TEMPLATE constants, helper functions, and wrap_query function
    extracted_lines: list[str] = []
    in_relevant_block = False

    for i, line in enumerate(lines):
        stripped = line.strip()
        # Skip imports and main() function
        if stripped.startswith(("import ", "from ", "if __name__")):
            continue
        if stripped.startswith("def main("):
            break
        # Include TEMPLATE strings, helper functions, and wrap_query
        if (
            stripped.startswith("TEMPLATE")
            or stripped.startswith("def ")
            or in_relevant_block
        ):
            extracted_lines.append(line)
            # Track triple-quote blocks
            triple_count = line.count('"""') + line.count("'''")
            if triple_count == 1:
                in_relevant_block = not in_relevant_block
            elif triple_count == 0 and not in_relevant_block:
                # Check if this is a continuation of a function (indented)
                if (
                    line
                    and not line[0].isspace()
                    and not stripped.startswith(("TEMPLATE", "def "))
                ):
                    extracted_lines.pop()
        elif in_relevant_block:
            extracted_lines.append(line)

    result = "\n".join(extracted_lines).strip()
    if not result or "wrap_query" not in result:
        # Fallback: extract everything between first TEMPLATE/def and main()
        start = -1
        end = len(lines)
        for i, line in enumerate(lines):
            if start == -1 and (
                line.strip().startswith("TEMPLATE")
                or (line.strip().startswith("def ") and "main" not in line)
            ):
                start = i
            if line.strip().startswith("def main("):
                end = i
                break
        if start >= 0:
            result = "\n".join(lines[start:end]).strip()

    return result


